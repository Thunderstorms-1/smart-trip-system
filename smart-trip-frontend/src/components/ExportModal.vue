<script setup>
import { ref, computed } from 'vue'
import QrcodeVue from 'qrcode.vue'
import html2canvas from 'html2canvas'
import jsPDF from 'jspdf'
import { useTripStore } from '@/stores/trip'

const props = defineProps({
  tripId: { type: [Number, String], required: true },
  visible: { type: Boolean, default: false }
})
defineEmits(['close'])

const tripStore = useTripStore()
const isExporting = ref(false)

const shareUrl = computed(() => {
  return `${window.location.origin}/trip/share/${props.tripId}`
})

const getItemTypeLabel = (type) => {
  const map = { SCENIC: '景点', FOOD: '美食', HOTEL: '住宿', TRAFFIC: '交通' }
  return map[type] || '活动'
}

const copyLink = async () => {
  try {
    await navigator.clipboard.writeText(shareUrl.value)
    alert('已复制分享链接到剪贴板！')
  } catch (e) {
    alert('复制失败，请手动复制输入框内的链接')
  }
}

// 导出 PNG 高清海报
const handleExportImage = async () => {
  const el = document.getElementById('print-trip-content')
  if (!el) return
  isExporting.value = true
  try {
    const canvas = await html2canvas(el, { scale: 2, useCORS: true })
    const imgData = canvas.toDataURL('image/png')
    const link = document.createElement('a')
    link.href = imgData
    link.download = `${tripStore.currentTrip.title || '旅行路书'}_海报.png`
    link.click()
  } catch (err) {
    console.error('导出图片失败:', err)
    alert('导出海报失败，请稍后重试')
  } finally {
    isExporting.value = false
  }
}

// 导出 A4 分页 PDF
const handleExportPDF = async () => {
  const el = document.getElementById('print-trip-content')
  if (!el) return
  isExporting.value = true
  try {
    const canvas = await html2canvas(el, { scale: 2, useCORS: true })
    const contentWidth = canvas.width
    const contentHeight = canvas.height
    
    // A4 宽高标准点数 (595.28 x 841.89)
    const pageHeight = (contentWidth / 592.28) * 841.89
    let leftHeight = contentHeight
    let position = 0
    const imgWidth = 595.28
    const imgHeight = (592.28 / contentWidth) * contentHeight

    const pageData = canvas.toDataURL('image/jpeg', 1.0)
    const pdf = new jsPDF('', 'pt', 'a4')

    if (leftHeight < pageHeight) {
      pdf.addImage(pageData, 'JPEG', 0, 0, imgWidth, imgHeight)
    } else {
      while (leftHeight > 0) {
        pdf.addImage(pageData, 'JPEG', 0, position, imgWidth, imgHeight)
        leftHeight -= pageHeight
        position -= 841.89
        if (leftHeight > 0) {
          pdf.addPage()
        }
      }
    }
    pdf.save(`${tripStore.currentTrip.title || '旅行路书'}.pdf`)
  } catch (err) {
    console.error('导出PDF失败:', err)
    alert('导出PDF失败，请稍后重试')
  } finally {
    isExporting.value = false
  }
}
</script>

